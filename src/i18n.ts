export function formatBirthDate(value: string, language: Language): string {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return value;
  const [year, month, day] = value.split('-').map(Number);
  const date = new Date(year, month - 1, day);
  if (date.getFullYear() !== year || date.getMonth() !== month - 1 || date.getDate() !== day) return value;
  const formatted = `${day} ${months[language][month - 1]} ${year}`;
  const digits = language === 'en' ? '0123456789' : language === 'gu' ? '૦૧૨૩૪૫૬૭૮૯' : '०१२३४५६७८९';
  return formatted.replace(/\d/g, digit => digits[Number(digit)]);
}
